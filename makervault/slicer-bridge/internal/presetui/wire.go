func serve(input io.Reader, output io.Writer, platform string, action func(request) (string, error)) int {
	data, err := io.ReadAll(io.LimitReader(input, MaxRequestBytes+1))
	var req request
	res := response{Version: 1}
	if err != nil || decode(data, &req, MaxRequestBytes) != nil || !validRequest(req) {
		res.Code = "ui_request_invalid"
	} else if platform != "windows" {
		res.Code = "ui_platform_unsupported"
	} else {
		res.Path, err = action(req)
		if err != nil {
			res.Path = ""
			res.Code = "ui_unavailable"
			if c, ok := err.(Code); ok && allowedCode(c) {
				res.Code = c
			}
		}
		if err == nil && ((req.Operation == "browser" && res.Path != "") || (req.Operation == "folder" && !validRoot(platform, res.Path))) {
			res.Path = ""
			res.Code = "ui_selection_rejected"
		}
	}
	data, err = json.Marshal(res)
	if err != nil || len(data) > MaxResponseBytes {
		data, _ = json.Marshal(response{Version: 1, Code: "ui_response_limit"})
	}
	if _, err = output.Write(data); err != nil {
		return 1
	}
	return 0
}
