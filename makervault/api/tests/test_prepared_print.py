def test_attached_and_embedded_prepared_payloads_match(client: TestClient) -> None:
    headers = auth_header(client)
    primary = client.post(
        "/upload",
        files={"file": ("cube.stl", b"solid cube\n", "model/stl")},
        headers=headers,
    )
    assert primary.status_code == 200, primary.text
    asset_id = primary.json()["id"]

    attached = client.post(
        f"/asset/{asset_id}/files",
        files={
            "file": (
                "print.gcode.3mf",
                fixture_bytes("prusaslicer_mk3s.gcode.3mf"),
                "model/3mf",
            )
        },
        headers=headers,
    )
    assert attached.status_code == 200, attached.text
    attached_payload = attached.json()["prepared_print"]

    embedded = client.post(
        "/upload",
        files={
            "file": (
                "print.gcode.3mf",
                fixture_bytes("prusaslicer_mk3s.gcode.3mf"),
                "model/3mf",
            )
        },
        headers=headers,
    )
    assert embedded.status_code == 200, embedded.text
    embedded_payload = embedded.json()["prepared_print"]

    assert attached_payload["removable"] is True
    assert embedded_payload["removable"] is False

    def without_removable(payload: dict) -> dict:
        return {key: value for key, value in payload.items() if key != "removable"}

    assert without_removable(attached_payload) == without_removable(embedded_payload)
    assert without_removable(attached_payload) == EXPECTED_FIXTURES["prusaslicer_mk3s.gcode.3mf"]


def test_legacy_metadata_blob_serialises_the_full_shape(client: TestClient) -> None:
    headers = auth_header(client)
    created = client.post(
        "/upload",
        files={"file": ("model.stl", b"solid model\n", "model/stl")},
        headers=headers,
    )
    assert created.status_code == 200, created.text
    asset_id = created.json()["id"]

    with Session(engine) as session:
        asset = session.get(Asset, asset_id)
        assert asset is not None
        asset.prepared_metadata_json = '{"format": "gcode"}'
